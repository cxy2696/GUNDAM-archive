export const dictionaries = { zh, ja };
export type Dictionary = typeof zh;

export function getDict(lang: Lang): Dictionary {
  return dictionaries[lang];
}

export function isLang(value: string): value is Lang {
  return value === "zh" || value === "ja";
}

export function pick<T extends { zh: string; ja?: string }>(value: T, lang: Lang): string {
  if (lang === "ja" && value.ja) return value.ja;
  return value.zh;
}

export function altLang(lang: Lang): Lang {
  return lang === "zh" ? "ja" : "zh";
}
