export const dictionaries = { zh, ja, en };
export type Dictionary = typeof zh;

export function getDict(lang: Lang): Dictionary {
  return dictionaries[lang];
}

export function isLang(value: string): value is Lang {
  return value === "zh" || value === "ja" || value === "en";
}

export function pick<T extends { zh: string; ja?: string; en?: string }>(value: T, lang: Lang): string {
  if (lang === "en") return value.en ?? value.zh;
  if (lang === "ja") return value.ja ?? value.zh;
  return value.zh;
}

/** Paragraph arrays follow the same fallback rule as single strings. */
export function sourceLabel(
  source: { label: string; labelEn?: string },
  lang: Lang,
): string {
  return lang === "en" ? source.labelEn ?? source.label : source.label;
}

export function sourceNote(
  source: { note?: string; noteEn?: string },
  lang: Lang,
): string | undefined {
  return lang === "en" ? source.noteEn ?? source.note : source.note;
}

export function pickList<T extends { zh: string[]; ja?: string[]; en?: string[] }>(
  value: T,
  lang: Lang,
): string[] {
  if (lang === "en") return value.en ?? value.zh;
  if (lang === "ja") return value.ja ?? value.zh;
  return value.zh;
}

/** Canonical hreflang set for a path such as "/machines" or "/machines/rx-78-2". */
export function languageAlternates(path = ""): Record<string, string> {
  const suffix = path ? (path.startsWith("/") ? path : `/${path}`) : "";
  const route = suffix.endsWith("/") ? suffix : `${suffix}/`;
  return {
    "zh-CN": `/zh${route}`,
    "ja-JP": `/ja${route}`,
    en: `/en${route}`,
    "x-default": `/zh${route}`,
  };
}

export function altLang(lang: Lang): Lang {
  if (lang === "zh") return "ja";
  if (lang === "ja") return "en";
  return "zh";
}
